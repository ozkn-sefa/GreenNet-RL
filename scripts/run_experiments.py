"""
Multi-seed comparison of OSPF/ECMP, Static, Threshold and PPO (raw and with safe-action filter)
on identical held-out traffic scenarios. Writes results/experiments.json and results/EXPERIMENT_REPORT.md.
Everything in the report is produced by this run.

Usage:
    python scripts/run_experiments.py --seeds 10 --steps 120
"""

import argparse
import json
import os
import sys
import time

if sys.platform.startswith("win"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from src.env.green_network_env import GreenNetworkEnv, TRAIN_SEED_LIMIT
from src.agents.baselines import OSPFBaselineAgent, StaticHeuristicAgent, ThresholdLoadAgent
from src.agents.rl_agent import GreenRLAgent
from src.agents.safety import SafeAgent
from src.agents.experiments import (
    TEST_SEED_BASE, METRICS, load_scenarios, run_matrix, aggregate, markdown_table, file_fingerprint,
)

SUMMARY_METRICS = [m for m, _ in METRICS]


def baseline_factories():
    return {
        "OSPF / ECMP": lambda env: OSPFBaselineAgent(env=env),
        "Static": lambda env: StaticHeuristicAgent(env=env),
        "Threshold": lambda env: ThresholdLoadAgent(env=env),
        "Threshold + SafeFilter": lambda env: SafeAgent(ThresholdLoadAgent(env=env), env),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=10)
    ap.add_argument("--steps", type=int, default=120)
    ap.add_argument("--model", default=os.path.join("models", "ppo_green_agent.zip"))
    ap.add_argument("--out", default=os.path.join("results", "experiments.json"))
    ap.add_argument("--report", default=os.path.join("results", "EXPERIMENT_REPORT.md"))
    ap.add_argument("--skip-scale", action="store_true", help="skip k=6 / NSFNET baseline scale tests")
    args = ap.parse_args()

    seeds = [TEST_SEED_BASE + i for i in range(args.seeds)]
    t0 = time.time()
    result = {"config": {"seeds": seeds, "steps": args.steps, "train_seed_limit": TRAIN_SEED_LIMIT}, "k4": {}, "scale": {}}

    # ---- k=4: all algorithms incl. PPO ------------------------------------------------
    env = GreenNetworkEnv(k=4, max_steps_per_episode=args.steps)
    factories = baseline_factories()
    ppo_available = os.path.exists(args.model)
    if ppo_available:
        probe = GreenRLAgent(env=env, algo="PPO", model_path=args.model, use_shield=False)
        if probe.is_trained:
            result["config"]["ppo_model"] = file_fingerprint(args.model)
            factories["PPO (raw)"] = lambda e: GreenRLAgent(env=e, algo="PPO", model_path=args.model, use_shield=False)
            factories["PPO + SafeFilter"] = lambda e: SafeAgent(
                GreenRLAgent(env=e, algo="PPO", model_path=args.model, use_shield=False), e)
        else:
            print("[!] PPO model could not be loaded for k=4; PPO rows omitted.")
    else:
        print(f"[!] {args.model} not found; PPO rows omitted.")

    print(f"[*] k=4 matrix: {len(load_scenarios())} scenarios x {len(seeds)} seeds x {len(factories)} agents")
    raw = run_matrix(env, factories, load_scenarios(), seeds, args.steps)
    result["k4"] = {"aggregate": aggregate(raw), "raw": raw}

    # ---- topology scale (baselines only; PPO is trained on k=4 observation size) ------------
    if not args.skip_scale:
        scale_sc = {k: v for k, v in load_scenarios().items() if k in ("diurnal@1.0", "datacenter_pareto@2.0", "flash_crowd@1.0")}
        for topo in ("fattree_k6", "nsfnet"):
            print(f"[*] scale test: {topo}")
            e = GreenNetworkEnv(topology_type=topo, max_steps_per_episode=args.steps)
            f = baseline_factories()
            r = run_matrix(e, f, scale_sc, seeds[: max(3, args.seeds // 2)], args.steps)
            result["scale"][topo] = {"aggregate": aggregate(r), "sla_delay_ms": e.sla_delay_ms,
                                      "n_seeds": max(3, args.seeds // 2)}

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=1, default=float)

    write_report(result, args.report, time.time() - t0)
    print(f"[+] {args.out}\n[+] {args.report}")


def write_report(result, path, elapsed):
    cfg = result["config"]
    agg = result["k4"]["aggregate"]
    L = ["# GreenNet-RL Experiment Report (auto-generated)", "",
         "Generated by `scripts/run_experiments.py`; every number comes from the executed simulation (no hand-edited values).", "",
         "## Protocol", "",
         f"- Test seeds: {cfg['seeds'][0]}..{cfg['seeds'][-1]} (n={len(cfg['seeds'])}), disjoint from training seeds [0, {cfg['train_seed_limit']}).",
         f"- Episode length: {cfg['steps']} steps (1 step = 720 s of simulated time; 120 steps = one diurnal day).",
         "- Cells: `mean ± std [95% CI]` over seeds (Student-t). Savings are paired per seed against OSPF/ECMP energy.",
         "- SLA violation step: avg end-to-end delay > SLA (3.5 ms fat-tree) or packet loss > 1%.",
         "- Energy / EEE / sleep / wake-up values are SIMULATED (analytical model); nothing is measured on hardware.",
         f"- PPO model: `{cfg['ppo_model']['path']}` sha256[:16]={cfg['ppo_model']['sha256_16']} (file mtime {cfg['ppo_model']['mtime']})."
         if "ppo_model" in cfg else "- PPO: not evaluated (model missing/unloadable).",
         f"- Runtime: {elapsed:.0f} s.", ""]
    L += ["## Overall (k=4, mean over all scenarios per seed)", "", markdown_table(agg["ALL (mean over scenarios)"], SUMMARY_METRICS), ""]
    for sc, block in agg.items():
        if sc.startswith("ALL"):
            continue
        L += [f"### Scenario `{sc}`", "", markdown_table(block, SUMMARY_METRICS), ""]
    if result["scale"]:
        L += ["## Topology scale (baselines only)", "",
              "PPO is not evaluated here: the shipped PPO is trained on the k=4 observation size.", ""]
        for topo, d in result["scale"].items():
            L += [f"### {topo} (SLA delay {d['sla_delay_ms']:.2f} ms, {d['n_seeds']} seeds)", "",
                  markdown_table(d["aggregate"]["ALL (mean over scenarios)"], SUMMARY_METRICS), ""]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L))


if __name__ == "__main__":
    main()
